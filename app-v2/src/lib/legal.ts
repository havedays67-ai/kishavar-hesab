export interface CompletenessCheck {
  label: string;
  ok: boolean;
  level: "required" | "recommended";
}

export interface CompletenessResult {
  score: number;
  complete: boolean;
  checks: CompletenessCheck[];
  missing: string[];
}

function hasText(value: unknown): boolean {
  return typeof value === "string" && value.trim().length > 1;
}

/**
 * کنترل کم‌وکسری سند؛ این کنترل قبل از چاپ/امضا نمایش داده می‌شود.
 * خالی‌بودن فیلد اختیاری، «کامل‌بودن» را از بین نمی‌برد، اما هشدار می‌دهد.
 */
export function documentCompleteness(
  spec: DocumentSpec,
  profile: { fullName?: string; nationalId?: string; phone?: string; address?: string; businessName?: string }
): CompletenessResult {
  const checks: CompletenessCheck[] = [];
  const add = (label: string, ok: boolean, level: CompletenessCheck["level"] = "required") => checks.push({ label, ok, level });

  add("شمارهٔ یکتای سند", hasText(spec.serial));
  add("تاریخ سند", Boolean(spec.date?.jy && spec.date?.jm && spec.date?.jd));
  add("نام کسب‌وکار", hasText(profile.businessName));
  add("نام/هویت کامل صادرکننده", hasText(profile.fullName));
  add("کد ملی / شناسهٔ ملی صادرکننده", hasText(profile.nationalId));
  add("نشانی و تلفن تماس", hasText(profile.phone) && hasText(profile.address));
  add("محل درج مهر و امضا", true);

  const trade = spec.payload.trade;
  const contract = spec.payload.contract;
  const cheque = spec.payload.cheque;
  if (trade) {
    add("نام خریدار/طرف‌حساب", hasText(trade.buyerName));
    add("مقدار و نرخ معامله", trade.result?.payableKg > 0 && trade.result?.netReceipt > 0);
    add("شمارهٔ قرارداد/چک (در صورت وجود)", Boolean(trade.chequeNo) || trade.paymentMethod !== "cheque", "recommended");
  }
  if (contract) {
    add("نام موجر/طرف‌حساب", hasText(contract.partyName));
    add("مدت و مال‌الاجاره", Boolean(contract.start && contract.end) && contract.rent > 0);
    add("مبلغ ودیعه", contract.deposit > 0, "recommended");
    add("شرح وضعیت زمین و حقابه", hasText(contract.landTitle));
  }
  if (cheque) {
    add("شناسهٔ یکتای ۱۶ رقمی صیاد", (cheque.sayadId ?? "").replace(/\D/g, "").length === 16);
    add("نام صاحب حساب", hasText(cheque.accountOwner));
    add("کد ملی/شناسهٔ صاحب حساب", (cheque.nationalId ?? "").replace(/\D/g, "").length >= 10);
    add("تاریخ صدور و سررسید", Boolean(cheque.issueDate && cheque.due));
    add("بابت/دلیل پرداخت", hasText(cheque.reason));
    add("شعبه، شماره حساب و شبا", hasText(cheque.branch) && (hasText(cheque.accountNo) || hasText(cheque.iban)), "recommended");
    add("آیا چک در سامانهٔ صیاد ثبت و توسط گیرنده تأیید شده است؟", false, "recommended");
  }

  const missing = checks.filter((check) => !check.ok && check.level === "required").map((check) => check.label);
  const total = checks.length || 1;
  const score = Math.round((checks.filter((check) => check.ok).length / total) * 100);
  return { score, complete: missing.length === 0, checks, missing };
}

