export function GuideCenter() {
  const [query, setQuery] = useState("");
  const [open, setOpen] = useState<string | null>("start");

  const topics = useMemo(() => {
    const needle = query.trim();
    if (!needle) return GUIDE_TOPICS;
    return GUIDE_TOPICS.filter((topic) =>
      [topic.title, topic.summary, ...topic.steps, ...topic.qa.map((item) => `${item.q} ${item.a}`)]
        .join(" ")
        .includes(needle),
    );
  }, [query]);

  return (
    <div className="space-y-3">
      <div className="glass flex flex-col gap-2 rounded-2xl p-3 sm:flex-row sm:items-center sm:justify-between">
        <div className="flex items-center gap-2 text-[10px] text-[#a9c1b5]">
          <Sparkles className="h-3.5 w-3.5 text-mint-300" />
          {topics.length} راهنما · روی هر کارت بزنید تا کامل باز شود
        </div>
        <div className="flex items-center gap-2">
          <label className="flex flex-1 items-center gap-1.5 rounded-lg border border-white/[0.08] bg-[#071510]/60 px-2 py-1.5 sm:w-56">
            <Search className="h-3 w-3 text-[#78968a]" />
            <input
              value={query}
              onChange={(event) => setQuery(event.target.value)}
              placeholder="جستجو در راهنما…"
              className="w-full bg-transparent text-[9px] text-[#dcebe2] outline-none placeholder:text-[#6f8c7f]"
              aria-label="جستجو در راهنما"
            />
          </label>
          <button
            type="button"
            onClick={() => setOpen(open ? null : "start")}
            className="shrink-0 rounded-lg border border-white/[0.09] px-2 py-1.5 text-[8px] text-[#b9cec3]"
          >
            {open ? "بستن همه" : "باز کردن اولی"}
          </button>
        </div>
      </div>

      <div className="grid gap-2.5 md:grid-cols-2">
        {topics.map((topic) => {
          const isOpen = open === topic.id;
          return (
            <section key={topic.id} className={cn("glass overflow-hidden rounded-2xl transition", isOpen && "border-mint-300/25")}>
              <button
                type="button"
                onClick={() => setOpen(isOpen ? null : topic.id)}
                aria-expanded={isOpen}
                className="flex w-full items-center justify-between gap-2 px-3.5 py-3 text-right"
              >
                <span className="flex min-w-0 items-center gap-2">
                  <span className={cn("grid h-7 w-7 shrink-0 place-items-center rounded-lg border text-[9px]", isOpen ? "border-mint-300/30 bg-mint-300/10 text-mint-300" : "border-white/[0.08] text-[#93ad9f]")}>
                    <BookOpen className="h-3.5 w-3.5" />
                  </span>
                  <span className="min-w-0">
                    <span className="block text-[10px] font-semibold text-[#e3f0e8]">{topic.title}</span>
                    <span className="mt-0.5 block truncate text-[8px] text-[#819d90]">{topic.summary}</span>
                  </span>
                </span>
                <ChevronDown className={cn("h-4 w-4 shrink-0 text-[#78968a] transition", isOpen && "rotate-180 text-mint-300")} />
              </button>
              {isOpen && (
                <div className="space-y-2.5 border-t border-white/[0.06] px-3.5 py-3">
                  <ol className="space-y-1.5">
                    {topic.steps.map((step, index) => (
                      <li key={step} className="flex gap-2 text-[9px] leading-5 text-[#c3d8cc]">
                        <span className="mt-0.5 grid h-4 w-4 shrink-0 place-items-center rounded bg-mint-300/10 text-[7px] font-bold text-mint-300">{index + 1}</span>
                        <span>{step}</span>
                      </li>
                    ))}
                  </ol>
                  {topic.pitfall && (
                    <p className="rounded-lg border border-sand-300/20 bg-sand-300/[0.05] px-2 py-1.5 text-[8px] leading-5 text-[#d5caa9]">
                      نکتهٔ خطا: {topic.pitfall}
                    </p>
                  )}
                  <div className="space-y-1.5">
                    {topic.qa.map((item) => (
                      <div key={item.q} className="rounded-lg border border-white/[0.05] bg-white/[0.02] px-2 py-1.5">
                        <p className="flex items-start gap-1 text-[8px] font-medium text-[#dcebe2]">
                          <HelpCircle className="mt-0.5 h-2.5 w-2.5 shrink-0 text-mint-300" />
                          {item.q}
                        </p>
                        <p className="mt-0.5 pr-3.5 text-[8px] leading-5 text-[#93ad9f]">{item.a}</p>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </section>
          );
        })}
      </div>
      {topics.length === 0 && (
        <p className="glass rounded-2xl p-4 text-center text-[9px] text-[#93ad9f]">برای این واژه راهنمایی پیدا نشد؛ واژهٔ کوتاه‌تری امتحان کنید.</p>
      )}
    </div>
  );
}
